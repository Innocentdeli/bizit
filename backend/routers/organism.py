"""
BIZIT Organism API Router
==========================
Exposes the Organism's live activity feed and control surface
to the frontend dashboard.
"""

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from routers.auth import get_current_user
from database.models import User
from sqlalchemy import func, desc
from database.database import get_db
from database.models import OrganismActivity, OrganismAlert, Business
from organism.scheduler import get_scheduler_status, start_organism, stop_organism
import time

router = APIRouter()


@router.get("/status")
def organism_status():
    """Current Organism scheduler status and job schedule."""
    status = get_scheduler_status()
    return {
        "organism": "BIZIT Autonomous Organism v1.0",
        "state": "ALIVE" if status["running"] else "DORMANT",
        **status,
    }


@router.get("/activity")
def get_activity(limit: int = 50, cycle: str = None, db: Session = Depends(get_db)):
    """
    Live activity feed — everything the Organism has done autonomously.
    Sorted newest first.
    """
    query = db.query(OrganismActivity).order_by(desc(OrganismActivity.timestamp))
    if cycle:
        query = query.filter(OrganismActivity.cycle == cycle.upper())
    activities = query.limit(limit).all()

    return {
        "count": len(activities),
        "activities": [
            {
                "id": a.id,
                "timestamp": a.timestamp,
                "cycle": a.cycle,
                "business_name": a.business_name,
                "action": a.action,
                "detail": a.detail,
                "impact": a.impact,
                "status": a.status,
                "autonomous": a.autonomous,
            }
            for a in activities
        ],
    }


@router.get("/alerts/{business_id}")
def get_alerts(business_id: str, db: Session = Depends(get_db)):
    """
    Proactive alerts generated by the Organism for a specific business.
    """
    alerts = (
        db.query(OrganismAlert)
        .filter(OrganismAlert.business_id == business_id)
        .order_by(desc(OrganismAlert.timestamp))
        .limit(20)
        .all()
    )
    return {
        "business_id": business_id,
        "unread": sum(1 for a in alerts if not a.read),
        "alerts": [
            {
                "id": a.id,
                "timestamp": a.timestamp,
                "priority": a.priority,
                "title": a.title,
                "body": a.body,
                "action_label": a.action_label,
                "read": a.read,
            }
            for a in alerts
        ],
    }


@router.post("/alerts/{alert_id}/read")
def mark_alert_read(alert_id: int, db: Session = Depends(get_db)):
    """Mark an alert as read."""
    alert = db.query(OrganismAlert).filter(OrganismAlert.id == alert_id).first()
    if not alert:
        raise HTTPException(status_code=404, detail="Alert not found")
    alert.read = True
    db.commit()
    return {"status": "ok"}


@router.get("/stats")
def organism_stats(db: Session = Depends(get_db)):
    """
    High-level Organism impact statistics.
    Shows how much value the Organism has autonomously created.
    """
    total_actions = db.query(OrganismActivity).count()
    cycles_done = (
        db.query(OrganismActivity.cycle, func.count(OrganismActivity.cycle).label("cnt"))
        .group_by(OrganismActivity.cycle)
        .all()
    )
    total_alerts = db.query(OrganismAlert).count()
    unread_alerts = db.query(OrganismAlert).filter(OrganismAlert.read == False).count()
    verifications = (
        db.query(OrganismActivity)
        .filter(OrganismActivity.cycle == "VERIFY")
        .count()
    )
    enrichments = (
        db.query(OrganismActivity)
        .filter(OrganismActivity.cycle == "ENRICH")
        .count()
    )
    last_action = (
        db.query(OrganismActivity)
        .order_by(desc(OrganismActivity.timestamp))
        .first()
    )

    return {
        "total_autonomous_actions": total_actions,
        "total_alerts_generated": total_alerts,
        "unread_alerts": unread_alerts,
        "verifications_run": verifications,
        "profiles_enriched": enrichments,
        "last_action_at": last_action.timestamp if last_action else None,
        "last_action": last_action.action if last_action else "None yet",
        "cycle_breakdown": {c: n for c, n in cycles_done},
    }


from fastapi import BackgroundTasks

@router.post("/trigger")
def trigger_cycle(background_tasks: BackgroundTasks):
    """
    Manually trigger an immediate full Organism cycle.
    Useful for testing or on-demand runs.
    """
    from organism.worker import run_organism_cycle_sync
    background_tasks.add_task(run_organism_cycle_sync)
    return {"status": "triggered", "message": "Organism cycle initiated."}

