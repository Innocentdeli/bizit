from auth.security import get_password_hash, create_access_token, ACCESS_TOKEN_EXPIRE_MINUTES
from datetime import timedelta
from pydantic import BaseModel
from typing import Optional

class ClaimPayload(BaseModel):
    email: Optional[str] = None
    password: Optional[str] = None
    full_name: Optional[str] = None
    phone: Optional[str] = None

@router.get("/claim/{token}")
def get_ghost_profile(token: str, db: Session = Depends(get_db)):
    """Fetch a ghost profile by its secure token with rich growth metrics."""
    biz = db.query(Business).filter(Business.ghost_token == token, Business.claimed == False).first()
    if not biz:
        # Check if already claimed
        claimed_biz = db.query(Business).filter(Business.ghost_token == token, Business.claimed == True).first()
        if claimed_biz:
            return {
                "id": claimed_biz.id,
                "name": claimed_biz.name,
                "already_claimed": True,
                "message": "This business has already been claimed."
            }
        raise HTTPException(status_code=404, detail="Invalid or expired claim token.")
    
    return {
        "id": biz.id,
        "name": biz.name,
        "category": biz.category,
        "location": biz.location,
        "description": biz.description or f"Leading {biz.category} specialist based in {biz.location}.",
        "source_url": biz.source_url,
        "photo_url": biz.photo_url or "https://images.unsplash.com/photo-1556740758-90de374c12ad?w=800&auto=format&fit=crop&q=60",
        "phone": biz.phone or "+234 800 000 0000",
        "website": biz.website,
        "services": biz.services or ["Core Products", "Custom Consultation", "Express Delivery", "Warranty Service"],
        "rating": biz.rating or 4.9,
        "review_count": biz.review_count or 18,
        "profile_views": max(biz.profile_views or 0, 184),
        "search_appearances": max(biz.search_appearances or 0, 420),
        "estimated_monthly_demand": 310,
        "ai_hook": f"Discover how {biz.name} delivers premier {biz.category.lower()} in {biz.location}. Fast, trusted, and locally verified.",
        "trial_days": 14,
        "already_claimed": False
    }

@router.post("/claim/{token}")
def claim_ghost_profile(
    token: str,
    payload: Optional[ClaimPayload] = None,
    db: Session = Depends(get_db)
):
    """
    Claim a ghost profile. Supports:
    1. Direct 1-click registration with email & password.
    2. Or linking to an existing user record.
    """
    biz = db.query(Business).filter(Business.ghost_token == token, Business.claimed == False).first()
    if not biz:
        raise HTTPException(status_code=404, detail="Invalid or expired claim token.")
    
    user = None
    access_token = None

    if payload and payload.email:
        email = payload.email.strip().lower()
        user = db.query(User).filter(User.email == email).first()
        if not user:
            pwd = payload.password or "DimaDefaultPassword2026!"
            hashed_password = get_password_hash(pwd)
            user = User(
                email=email,
                hashed_password=hashed_password,
                role="business_owner",
                business_id=biz.id
            )
            db.add(user)
            db.commit()
            db.refresh(user)
        else:
            user.business_id = biz.id
            user.role = "business_owner"
            db.commit()

        access_token_expires = timedelta(minutes=ACCESS_TOKEN_EXPIRE_MINUTES)
        access_token = create_access_token(
            data={"sub": user.email}, expires_delta=access_token_expires
        )
    
    # Mark business as claimed
    biz.claimed = True
    biz.contact_email = payload.email if payload and payload.email else biz.contact_email
    if payload and payload.phone:
        biz.phone = payload.phone
    db.commit()
    
    return {
        "status": "success",
        "message": f"Welcome to Dima, {biz.name}!",
        "business_id": biz.id,
        "business_name": biz.name,
        "access_token": access_token,
        "token_type": "bearer"
    }
